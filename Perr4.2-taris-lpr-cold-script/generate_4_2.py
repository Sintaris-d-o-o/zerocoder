# ── Части промпта: текст и ссылки на ячейки ───────────────────────────────────

@dataclass(frozen=True)
class Ref:
    cell: str
    sheet: str | None = None        # None — тот же лист

    def formula(self, here: str) -> str:
        return self.cell if self.sheet in (None, here) else f"'{self.sheet}'!{self.cell}"


Part = str | Ref


def concat_formula(parts: list[Part], sheet: str) -> str:
    """Части → =CONCATENATE(...). Текст режем на куски ≤250 символов и склеиваем через &,
    как в шаблоне урока: у строковых литералов в формулах есть ограничение длины."""
    args = []
    for p in parts:
        if isinstance(p, Ref):
            args.append(p.formula(sheet))
            continue
        chunks = [p[i:i + 250] for i in range(0, len(p), 250)] or [""]
        args.append("&".join('"' + c.replace('"', '""') + '"' for c in chunks))
    return "=CONCATENATE(" + ",".join(args) + ")"


class Book:
    """Значения ячеек (для сборки промптов) + сам xlsx."""

    def __init__(self) -> None:
        self.wb = Workbook()
        self.wb.remove(self.wb.active)
        self.vals: dict[tuple[str, str], str] = {}

    def ws(self, name: str):
        return self.wb[name] if name in self.wb.sheetnames else self.wb.create_sheet(name)

    def put(self, sheet: str, cell: str, value: str, *, bold: bool = False, fill: str | None = None) -> None:
        """Записать значение (текст). Значение, начинающееся с «=», Sheets принял бы за формулу."""
        if value.startswith("="):
            value = "​" + value
        c = self.ws(sheet)[cell]
        c.value = value
        c.alignment = Alignment(wrap_text=True, vertical="top")
        if bold:
            c.font = Font(bold=True)
        if fill:
            c.fill = PatternFill("solid", fgColor=fill)
        self.vals[(sheet, cell)] = value

    def put_formula(self, sheet: str, cell: str, formula: str, value: str) -> None:
        """Формула в ячейку, её вычисленное значение — в память для следующих промптов."""
        c = self.ws(sheet)[cell]
        c.value = formula
        c.alignment = Alignment(wrap_text=True, vertical="top")
        self.vals[(sheet, cell)] = value

    def get(self, ref: Ref, sheet: str) -> str:
        return self.vals[(ref.sheet or sheet, ref.cell.replace("$", ""))]

    def render(self, parts: list[Part], sheet: str) -> str:
        return "".join(self.get(p, sheet) if isinstance(p, Ref) else p for p in parts)

    def prompt_cell(self, sheet: str, cell: str, parts: list[Part]) -> str:
        """Ячейка «Промпт»: чистый текст — значением, со ссылками — формулой CONCATENATE."""
        text = self.render(parts, sheet)
        if any(isinstance(p, Ref) for p in parts):
            self.put_formula(sheet, cell, concat_formula(parts, sheet), text)
        else:
            self.put(sheet, cell, text)
        return text


# ── ChatGPT с кэшем ───────────────────────────────────────────────────────────

class GPT:
    def __init__(self, api_key: str) -> None:
        self.client = OpenAI(api_key=api_key)
        RESULTS.mkdir(exist_ok=True)
        self.cache = json.loads(CACHE_PATH.read_text(encoding="utf-8")) if CACHE_PATH.exists() else {}
        self.log: list[dict] = []
        self.calls = 0

    def _save_cache(self) -> None:
        """Через временный файл и с повторами: на Windows кэш иногда на миг держит другой процесс
        (антивирус, индексатор редактора), и прямая запись падает с OSError [Errno 22]."""
        tmp = CACHE_PATH.with_suffix(".tmp")
        for attempt in range(5):
            try:
                tmp.write_text(json.dumps(self.cache, ensure_ascii=False, indent=1), encoding="utf-8")
                tmp.replace(CACHE_PATH)
                return
            except OSError:
                time.sleep(1 + attempt)
        print("    ! кэш не сохранён (файл занят) — ответы останутся в памяти до конца запуска",
              file=sys.stderr)

    def __call__(self, label: str, prompt: str) -> str:
        key = hashlib.sha256(f"{MODEL}\n{prompt}".encode()).hexdigest()
        if key not in self.cache:
            print(f"  → {label}", flush=True)
            for attempt in range(3):
                try:
                    resp = self.client.chat.completions.create(
                        model=MODEL, temperature=0,
                        messages=[{"role": "user", "content": prompt}])
                    self.cache[key] = resp.choices[0].message.content.strip()
                    self.calls += 1
                    break
                except Exception as exc:  # noqa: BLE001 — повторяем и показываем ошибку
                    print(f"    ! ошибка ({attempt + 1}/3): {exc}", file=sys.stderr)
                    time.sleep(3)
            else:
                raise RuntimeError(f"Нет ответа для шага «{label}»")
            self._save_cache()
        answer = self.cache[key]
        self.log.append({"шаг": label, "промпт": prompt, "ответ": answer})
        return answer


def gpt_list(gpt: GPT, label: str, prompt: str, n: int) -> list[str]:
    """Аналог =GPT_LIST(): ответ списком, каждый пункт — в отдельную ячейку."""
    lines = [re.sub(r"^\s*(?:\d+[.)]|[-*•])\s*", "", l).strip()
             for l in gpt(label, prompt + LIST_HINT).splitlines()]
    items = [l for l in lines if l]
    if len(items) != n:
        raise RuntimeError(f"«{label}»: ожидалось {n} пунктов, получено {len(items)}")
    return items


def split_sections(text: str, marker: str, n: int, label: str) -> list[str]:
    """Разбить ответ по заголовкам вида «### Сегмент 1: …» на n частей (заголовок остаётся в части)."""
    parts = re.split(rf"(?m)^(?=\s*[#*]*\s*{marker}\s*\d)", text)
    parts = [p.strip() for p in parts if re.match(rf"\s*[#*]*\s*{marker}\s*\d", p)]
    if len(parts) != n:
        raise RuntimeError(f"«{label}»: ожидалось {n} разделов «{marker} N», найдено {len(parts)}")
    return parts


