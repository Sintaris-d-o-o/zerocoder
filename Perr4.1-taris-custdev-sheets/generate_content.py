def build_workbook(chain_results, formula_results, out_path: Path) -> None:
    wb = Workbook()

    header_font = Font(bold=True)
    wrap = Alignment(wrap_text=True, vertical="top")

    # --- Лист 1: продукт ---
    ws1 = wb.active
    ws1.title = "1. Продукт"
    ws1["A1"] = "Описание продукта"
    ws1["A1"].font = header_font
    ws1["A2"] = PRODUCT_DESCRIPTION
    ws1["A2"].alignment = wrap
    ws1.merge_cells("A2:D2")
    ws1.row_dimensions[2].height = 60

    headers = ["Категория", "Промпт (что отправляли в GPT)", "Пример формулы в Google Sheets", "Результат"]
    for col, title in enumerate(headers, start=1):
        cell = ws1.cell(row=4, column=col, value=title)
        cell.font = header_font

    row = 5
    for category, prompt_text, formula_example, answer in chain_results:
        ws1.cell(row=row, column=1, value=category).alignment = wrap
        ws1.cell(row=row, column=2, value=prompt_text).alignment = wrap
        ws1.cell(row=row, column=3, value=formula_example).alignment = wrap
        ws1.cell(row=row, column=4, value=answer).alignment = wrap
        row += 1

    widths1 = [22, 45, 40, 60]
    for i, w in enumerate(widths1, start=1):
        ws1.column_dimensions[get_column_letter(i)].width = w

    # --- Лист 2: тестирование формул ---
    ws2 = wb.create_sheet("2. Тест формул")
    headers2 = ["№", "Тип формулы", "Что означает", "Что подставляем (пример)", "Результат (эталон)"]
    for col, title in enumerate(headers2, start=1):
        cell = ws2.cell(row=1, column=col, value=title)
        cell.font = header_font

    for i, (formula, meaning, sample_input, result) in enumerate(formula_results, start=1):
        ws2.cell(row=i + 1, column=1, value=i)
        ws2.cell(row=i + 1, column=2, value=formula).alignment = wrap
        ws2.cell(row=i + 1, column=3, value=meaning).alignment = wrap
        ws2.cell(row=i + 1, column=4, value=sample_input).alignment = wrap
        ws2.cell(row=i + 1, column=5, value=result).alignment = wrap

    widths2 = [5, 30, 35, 45, 55]
    for i, w in enumerate(widths2, start=1):
        ws2.column_dimensions[get_column_letter(i)].width = w

    # --- Лист 3: идеи проектов ---
    ws3 = wb.create_sheet("3. Идеи проектов")
    headers3 = ["№", "Идея", "Как поможет в реальной работе"]
    for col, title in enumerate(headers3, start=1):
        cell = ws3.cell(row=1, column=col, value=title)
        cell.font = header_font

    for i, (idea, explanation) in enumerate(PROJECT_IDEAS, start=1):
        ws3.cell(row=i + 1, column=1, value=i)
        ws3.cell(row=i + 1, column=2, value=idea).alignment = wrap
        ws3.cell(row=i + 1, column=3, value=explanation).alignment = wrap

    widths3 = [5, 35, 70]
    for i, w in enumerate(widths3, start=1):
        ws3.column_dimensions[get_column_letter(i)].width = w

    wb.save(out_path)


def main():
    env = load_env(ENV_PATH)
    api_key = env.get("OPENAI_API_KEY")
    if not api_key:
        raise SystemExit("OPENAI_API_KEY не найден в .env")

    client = OpenAI(api_key=api_key)

    results = {}
    chain_rows = []
    print(f"Генерирую 17 пунктов кастдева для «Тариса» (модель {MODEL})...")
    for category, prompt_fn, formula_example in CHAIN:
        prompt_text = prompt_fn(results)
        print(f"  -> {category}")
        answer = ask(client, prompt_text)
        results[category] = answer
