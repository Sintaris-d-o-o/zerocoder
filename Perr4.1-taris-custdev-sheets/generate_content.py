def load_env(path: Path) -> dict:
    env = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        env[key.strip()] = value.strip()
    return env


def ask(client: OpenAI, prompt: str, temperature: float = 0) -> str:
    for attempt in range(3):
        try:
            resp = client.chat.completions.create(
                model=MODEL,
                messages=[{"role": "user", "content": prompt}],
                temperature=temperature,
            )
            return resp.choices[0].message.content.strip()
        except Exception as exc:  # noqa: BLE001 - просто ретраим и логируем
            print(f"  ! ошибка ({attempt + 1}/3): {exc}", file=sys.stderr)
            time.sleep(2)
    raise RuntimeError(f"Не удалось получить ответ для промпта: {prompt[:80]}...")


